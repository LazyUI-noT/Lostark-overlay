using System.Text;
using GaugeOverlay.Core.Domain;
using GaugeOverlay.Core.Vision;

namespace GaugeOverlay.Tests;

/// <summary>심판's icon in the buff row (단심, user 2026-10-13). Kept apart from the party buffs (BuffKind): it is the
/// player's own, read only when 단심 is on, and timed by its trigger alone.</summary>
public class JudgmentReaderTests
{
    // 단죄 폰트 변경 + 심판 효과 at 100%.mp4 from 47.5 s and 단죄여려번.mp4 whole, 1080p, HUD 110, buff 120%, origin (700, 886).
    static readonly PixelRect Row = new(700, 886, 150, 60);
    static readonly (string Fixture, Viewport Vp, Fit Fit, int Buff, PixelRect Rect) Judg = ("judg_row", Fhd, new Fit(110), 120, Row);

    // Every buff row in the fixtures, as recorded (BuffReaderTests, BuffSizeTests), ten boxes deep (the row 단심 reads).
    static readonly (string Name, Viewport Vp, Fit Fit, int Buff)[] Rows =
    [
        .. new[] { "buffrow_bg", "buffrow_wrong", "buffrow_dbl", "buffrow_dohwa1", "buffrow_dohwa2", "buffrow_gzbug", "dz_row", "judg_row" }
            .Select(n => (n, Fhd, new Fit(110), 120)),
        ("buffrow_b80", Fhd, new Fit(110), 80),
        ("buffrow_down", new Viewport(0, 135, 1920, 810), new Fit(100), 100),
        ("buffrow_hud80", Fhd, new Fit(80), 120),
        ("buffrow_hud90", Fhd, new Fit(90), 120),
    ];

    /// <summary>The boxes inside a fixture's crop, relative to it.</summary>
    static IEnumerable<(int Box, PixelRect Icon)> BoxesIn(Fixture f, Viewport vp, Fit fit, int buff) =>
        Geometry.BuffBoxes(vp, fit, buff, Geometry.JudgmentBoxCount)
            .Select((b, i) => (i, b.Icon with { X = b.Icon.X - f.Rect[0], Y = b.Icon.Y - f.Rect[1] }))
            .Where(b => b.Item2.X >= 0 && b.Item2.Y >= 0 && b.Item2.Right <= f.Frames[0].Width && b.Item2.Bottom <= f.Frames[0].Height);

    // 심판 replaces 단죄 in box 0 at 48.2 s: 0.99+ from that frame on. Nothing else in any row comes above 0.74 (blue party
    // buffs, hue 20° off; the spear beside 단죄 0.6), so MinIcon sits between (2026-10-13).
    [Fact]
    public void 심판_is_found_from_its_first_frame_and_nothing_else_ever_is()
    {
        var wrong = new List<string>();
        foreach (var (name, vp, fit, buff) in Rows)
        {
            var f = Fixture.Load(name);
            for (int i = 0; i < f.Frames.Count; i++)
                foreach (var (box, icon) in BoxesIn(f, vp, fit, buff))
                {
                    bool want = name == "judg_row" && box == 0 && f.Pts[i].TotalSeconds >= 48.15;
                    if (JudgmentReader.IsIcon(f.Frames[i], icon) != want) wrong.Add($"{name} {f.Pts[i].TotalSeconds:0.00} s box {box}");
                }
        }
        Assert.Empty(wrong);
    }

    // Read as the engine reads it: the icon, and its timer under it ("5초", "4초" from 49.15 s, so 심판 began at 48.15 s).
    [Fact]
    public void Read_through_the_tracker_the_icon_and_its_timer_date_the_trigger()
    {
        var f = Fixture.Load("judg_row");
        var box = BuffReaderTests.Boxes(Judg)[0];
        var timers = new BuffReader(Geometry.BuffScale(Fhd, 120));
        var s = JudgmentState.Ready;
        var dated = new List<double>();
        var shown = new List<double?>();
        for (int i = 0; i < f.Frames.Count; i++)
        {
            bool on = JudgmentReader.IsIcon(f.Frames[i], box.Icon);
            double? timer = on ? timers.ReadTimer(f.Frames[i], box.Timer) : null;
            if (on) shown.Add(timer);
            var next = Core.Cooldown.JudgmentTracker.Update(s, new(on, false, timer), f.Pts[i], hudVisible: true);
            if (next.TriggeredAt != s.TriggeredAt) dated.Add(next.TriggeredAt!.Value.TotalSeconds);
            s = next;
        }
        Assert.Equal([5, 4, 3, 2, 1, 0.9, 0.8], shown.OfType<double>().Select(t => Math.Round(t, 1)).Distinct());   // every second, then tenths to the clip's end
        Assert.All(dated, t => Assert.InRange(t, 48.15 - 0.3, 48.15 + 0.3));   // first sighting, then the ticks
        Assert.InRange(s.TriggeredAt!.Value.TotalSeconds, 48.15 - 0.12, 48.15 + 0.12);
    }

    [Fact]
    public void Build_judgment_templates_when_requested()
    {
        if (Environment.GetEnvironmentVariable("GAUGE_BUILD_TEMPLATES") != "1") return;
        string Cut(string fixture, int frame, int box) =>
            Convert.ToBase64String(BuffReaderTests.Crop(Fixture.Load(fixture).Frames[frame], BuffReader.Interior(BuffReaderTests.Boxes(Judg)[box].Icon)).ToBytes());
        var sb = new StringBuilder();
        sb.AppendLine("namespace GaugeOverlay.Core.Vision;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>심판's icon, frame left out (BuffReader.Interior), cut at buff 120% from 단죄 폰트 변경 + 심판 효과 at 100%.mp4 (49.0 s, box 0),");
        sb.AppendLine("/// and the icons that come closest to it. Image.ToBytes as base64. Generated by");
        sb.AppendLine("/// JudgmentReaderTests.Build_judgment_templates_when_requested (GAUGE_BUILD_TEMPLATES=1); do not edit by hand.</summary>");
        sb.AppendLine("internal static class JudgmentTemplates");
        sb.AppendLine("{");
        sb.AppendLine($"    public const string Icon = \"{Cut("judg_row", 15, 0)}\";");
        sb.AppendLine();
        // The words over the character, as JudgmentText's grids: "심판" settled at 100% (48.6 s), "단죄" at 100% (46.69 s).
        string Text(string fixture, int frame) =>
            JudgmentText.Encode(JudgmentText.Grid(JudgmentText.Words(Fixture.Load(fixture).Frames[frame]).MaxBy(w => w.Box.Height)));
        sb.AppendLine("    /// <summary>The words over the character as JudgmentText's grids: \"심판\" at 100% (48.6 s), \"단죄\" at 100% (46.69 s).</summary>");
        sb.AppendLine($"    public const string TextJudgment = \"{Text("judg_text", 6)}\", TextConviction = \"{Text("dz_text_100b", 0)}\";");
        sb.AppendLine();
        sb.AppendLine("    public static readonly string[] LookAlikes =");
        sb.AppendLine("    [");
        sb.AppendLine($"        \"{Cut("dz_row", 16, 1)}\",   // the blue spear buff beside 단죄 (단죄여려번.mp4, 4.0 s, box 1)");
        sb.AppendLine("    ];");
        sb.AppendLine("}");
        File.WriteAllText(Path.Combine(RepoRoot(), "Core", "Vision", "JudgmentTemplates.cs"), sb.ToString().ReplaceLineEndings("\r\n"));
    }
}
