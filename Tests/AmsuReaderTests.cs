    [Fact]
    public void Build_amsu_templates_when_requested()
    {
        if (Environment.GetEnvironmentVariable("GAUGE_BUILD_AMSU") != "1") return;
        static Image Cut(string fixture, PixelRect box)
        {
            var inner = new PixelRect(box.X + Inset, box.Y + Inset, box.Width - 2 * Inset, box.Height - 2 * Inset);
            return ImageOps.Resample(Fixture.Load(fixture).Frames[0], inner, (double)IconSide / inner.Width);
        }
        var cut = Cut("amsu_15", AmsuBox15);
        var bitam = Cut("bitam_120", BitamBox120);
        var sb = new StringBuilder();
        sb.AppendLine("namespace GaugeOverlay.Core.Vision;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>The boss row's bomb icons (Bomb order), frame left out, 25×25: 암수 cut from amsu_15 (a 2560×1080 game at 보스 디버프");
        sb.AppendLine("/// 크기 100), 빛암 from bitam_120 (1920×1080 at 120%). Image.ToBytes as base64.");
        sb.AppendLine("/// Generated by AmsuReaderTests.Build_amsu_templates_when_requested (GAUGE_BUILD_AMSU=1); do not edit by hand.</summary>");
        sb.AppendLine("internal static class AmsuTemplates");
        sb.AppendLine("{");
        sb.AppendLine("    public static readonly string?[] Icons =");
        sb.AppendLine("    [");
        sb.AppendLine($"        \"{Convert.ToBase64String(cut.ToBytes())}\",   // 암수");
        sb.AppendLine($"        \"{Convert.ToBase64String(bitam.ToBytes())}\",   // 빛암");
        sb.AppendLine("    ];");
        sb.AppendLine("}");
        File.WriteAllText(Path.Combine(RepoRoot(), "Core", "Vision", "AmsuTemplates.cs"), sb.ToString().ReplaceLineEndings("\r\n"));
    }

    // The reader as the engine runs it: the strip Geometry.BossRowSearch gives on the 21:9 clip (HUD 100, 보스 디버프 크기 100), the row
    // line RowLock settled there (game y 154: strip y 34), and the text at 보스 디버프 크기 100 on a 1080-high game.
    static readonly Viewport Wide = new(0, 0, 2560, 1080);
    static readonly Fit Hud100 = new(100);
    const int ClipRowY = 34;
    static double Scale => Geometry.BossScale(Wide, Hud100, 100);
    static double TextScale => Geometry.BuffScale(Wide, 100);
    static BossSlots WideSlots => Geometry.BossSlotsIn(Wide, Hud100, 100);
    static BossSlots HdSlots(int size) => Geometry.BossSlotsIn(Hd, Hud100, size);

    static Image Strip(string name)
    {
        var s = Geometry.BossRowSearch(Wide, Hud100, 100);
        return Fixture.Load(name).Frames[0].Crop(new PixelRect(s.X - 1000, s.Y - 100, s.Width, s.Height));
    }

