namespace GaugeOverlay.Tests;

public class BuffTimerTests
{
    /// <summary>Every labelled timer in buff_gameplay: frame, box and the text shown.</summary>
    internal static IEnumerable<(int Frame, int Box, double Seconds)> BgSamples()
    {
        for (int i = 0; i < BgLabels.Length; i++)
        {
            int n = 0;
            for (int b = 0; b < BgLabels[i].Length; b++)
                if (Label(BgLabels[i][b]) is not null) yield return (i * 5, b, BgTimers[i][n++]);
        }
    }

    internal static string Text(double seconds) => seconds < 1 ? seconds.ToString("0.0", CultureInfo.InvariantCulture) : ((int)seconds).ToString(CultureInfo.InvariantCulture);

    // How much each buff size's text is enlarged to reach the 120% cells, at 1080: the factor at which the 120% '초'
    // finds the most buff_80_to_110 timers (ZzProbe scan, steps of 0.025): 80% 48/49, 90% 62/64, 100% 55/55, 110% 68/68.
    static readonly Dictionary<int, double> Enlarge = new() { [80] = 1.825, [90] = 1.525, [100] = 1.40, [110] = 1.10, [120] = 1.0 };

    /// <summary>One learning sample: the frame, the timer rect in it, the buff size and the text shown.</summary>
    static IEnumerable<(Image Img, PixelRect Timer, int Size, double Seconds)> LearningSamples()
    {
        var bg = Fixture.Load(Bg.Fixture);
        var bgBoxes = Boxes(Bg);
        foreach (var (frame, box, seconds) in BgSamples()) yield return (bg.Frames[frame], bgBoxes[box].Timer, 120, seconds);
        var b80 = Fixture.Load(BuffSizeTests.B80.Fixture);
        foreach (var (second, box, seconds) in BuffSizeTests.Samples())
            yield return (b80.Frames[2 * second], Boxes(BuffSizeTests.At(second))[box].Timer, BuffSizeTests.SizeAt(second), seconds);
    }

    /// <summary>Rewrites Core/Vision/BuffGlyphs.cs: for each buff size, '초', the digits and '.', each the mean of every
    /// learning sample's glyph after enlarging the text to the 120% cells, located from '초' (found with the 120% '초')
    /// leftwards in fixed cells (digit 7 px, '.' 4 px, measured at 120%). Runs only with GAUGE_BUILD_TEMPLATES=1.</summary>
    [Fact]
    public void Build_buff_glyphs_when_requested()
    {
        if (Environment.GetEnvironmentVariable("GAUGE_BUILD_TEMPLATES") != "1") return;
        const int H = 12, ChoW = 14, DigitW = 7, DotW = 4, Margin = 2;
        // The 120% '초', read from the raw set (the reader's own sets may be mid-rewrite).
        var seed = BuffGlyphs.Sets.First(s => s.Size == 120).Glyphs.First(g => g.Ch == '초').Rows
            .SelectMany(r => r.Select(c => DigitReader.GreyRamp.IndexOf(c) * 28.3f)).ToArray();
        var sets = new SortedDictionary<int, SortedDictionary<char, (double[] Sum, int W, int N)>>();
        foreach (var (img, timer, size, seconds) in LearningSamples())
        {
            if (!sets.TryGetValue(size, out var sums)) sets[size] = sums = [];
            void Add(char ch, float[] cell, int w)
            {
                if (!sums.TryGetValue(ch, out var s)) s = (new double[w * H], w, 0);
                for (int i = 0; i < cell.Length; i++) s.Sum[i] += cell[i];
                sums[ch] = (s.Sum, w, s.N + 1);
            }
            var text = BuffReader.Resample(img, new PixelRect(timer.X, timer.Y - Margin, timer.Width, timer.Height + 2 * Margin), Enlarge[size]);
            var (cx, cy) = BuffReader.Find(text, new PixelRect(0, 0, text.Width, text.Height), seed, ChoW, H);
            Add('초', BuffReader.Luma(text, new PixelRect(cx, cy, ChoW, H)), ChoW);
            int x = cx;
            foreach (char ch in Text(seconds).Reverse())
            {
                x -= ch == '.' ? DotW : DigitW;
                if (x < 0) break;
                Add(ch, BuffReader.Luma(text, new PixelRect(x, cy, ch == '.' ? DotW : DigitW, H)), ch == '.' ? DotW : DigitW);
            }
        }
        var sb = new StringBuilder();
        sb.AppendLine("namespace GaugeOverlay.Core.Vision;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>The buff timer's glyphs, one set per in-game buff size at 1080: per-pixel mean luminance of labelled timers");
        sb.AppendLine("/// (120%: buff_gameplay.mp4; 80–110%: buff_80_to_110.mp4), each enlarged by the set's Enlarge to the");
        sb.AppendLine("/// 120% cells. Generated by BuffTimerTests.Build_buff_glyphs_when_requested (GAUGE_BUILD_TEMPLATES=1); do not edit by hand.");
        sb.AppendLine("/// One string per row; DigitReader.GreyRamp gives luminance 0..255 in 10 steps.</summary>");
        sb.AppendLine("internal static class BuffGlyphs");
        sb.AppendLine("{");
        sb.AppendLine("    public static readonly (int Size, double Enlarge, (char Ch, string[] Rows)[] Glyphs)[] Sets =");
        sb.AppendLine("    [");
        foreach (var (size, sums) in sets)
        {
            sb.AppendLine($"        ({size}, {Enlarge[size].ToString(CultureInfo.InvariantCulture)},");
            sb.AppendLine("        [");
            foreach (var (ch, (sum, w, n)) in sums)
            {
                var rows = Enumerable.Range(0, H).Select(y => new string([.. Enumerable.Range(0, w).Select(x => DigitReaderRamp(sum[y * w + x] / n))]));
                sb.AppendLine($"            ('{ch}', [{string.Join(", ", rows.Select(r => $"\"{r}\""))}]),   // {n} samples");
            }
            sb.AppendLine("        ]),");
        }
        sb.AppendLine("    ];");
        sb.AppendLine("}");
        File.WriteAllText(Path.Combine(RepoRoot(), "Core", "Vision", "BuffGlyphs.cs"), sb.ToString().ReplaceLineEndings("\r\n"));
    }

    [Fact]
    public void Reads_every_labelled_timer_in_buff_gameplay()
    {
        var f = Fixture.Load(Bg.Fixture);
        var boxes = Boxes(Bg);
        var reader = new BuffReader(Geometry.BuffScale(Bg.Vp, Bg.Buff));
        var wrong = BgSamples().Select(s => (s, got: reader.ReadTimer(f.Frames[s.Frame], boxes[s.Box].Timer)))
            .Where(r => r.got != r.s.Seconds).Select(r => $"frame {r.s.Frame} box {r.s.Box}: {r.s.Seconds} read {r.got?.ToString() ?? "null"}").ToList();
        Assert.True(wrong.Count == 0, string.Join(" | ", wrong));
    }

    /// <summary>도화가 clips (buff 120%, crop 600,870): last-second timers whose dot matches faintly (0.30–0.59) while the "0"
    /// before it is clear (0.81+) are tenths, not whole seconds ("0.9초" was read as 9); the AoE's whole "1초" stays 1, and whole
    /// timers with a tens 2 ("23초", "20초") stay whole.</summary>
    [Theory]
    [InlineData("buffrow_dohwa1", 15.5, 2, 0.9)]
    [InlineData("buffrow_dohwa1", 15.6, 2, 0.8)]
    [InlineData("buffrow_dohwa1", 15.8, 2, 0.6)]
    [InlineData("buffrow_dohwa1", 16.1, 2, 0.3)]
    [InlineData("buffrow_dohwa1", 16.2, 2, 0.2)]
    [InlineData("buffrow_dohwa2", 7.6, 0, 0.6)]
    [InlineData("buffrow_dohwa2", 7.7, 0, 0.5)]
    [InlineData("buffrow_dohwa2", 18.5, 0, 0.9)]
    [InlineData("buffrow_dohwa2", 18.7, 0, 0.7)]
    [InlineData("buffrow_dohwa2", 19.2, 3, 0.8)]
    [InlineData("buffrow_dohwa2", 28.2, 1, 0.8)]
    [InlineData("buffrow_dohwa2", 28.5, 1, 0.5)]
    [InlineData("buffrow_dohwa1", 15.3, 2, 1.0)]
    [InlineData("buffrow_dohwa2", 18.4, 3, 1.0)]
    [InlineData("buffrow_dohwa2", 27.8, 1, 1.0)]
    [InlineData("buffrow_dohwa2", 12.5, 2, 23.0)]   // a whole timer with a tens 2: its 0 window lies on the 2, not a 0
    [InlineData("buffrow_dohwa2", 15.6, 2, 20.0)]
    public void A_faint_dot_before_a_clear_0_is_still_tenths(string fixture, double at, int box, double seconds)
    {
        var src = Bg with { Fixture = fixture, Rect = new(600, 870, 260, 90) };
        var f = Fixture.Load(fixture);
        var reader = new BuffReader(Geometry.BuffScale(src.Vp, src.Buff));
        Assert.Equal(seconds, reader.ReadTimer(f.Frames[(int)Math.Round(at * 10)], Boxes(src)[box].Timer));
    }

    static char DigitReaderRamp(double v) => " .:-=+*#%@"[Math.Clamp((int)(v * 10 / 256), 0, 9)];
}
