using static GaugeOverlay.Tests.Helpers;

namespace GaugeOverlay.Tests;

/// <summary>낙인 in the boss debuff row (BrandReader): the three icons from the user's shots (reference/낙인, reference/바드debuff.PNG).</summary>
public class BrandReaderTests
{
    // Each icon's frame by its red lines, fixture px: 도화가 3rd (screen x 990–1017, y 170–197), 홀나/발키리 4th (1021–1048), 바드 3rd
    // in its crop (x 104–129, y 28–53; the gold shield before it is not a 낙인).
    static readonly PixelRect DohwaBox = new(290, 70, 28, 28), HolyBox = new(321, 70, 28, 28), BardBox = new(104, 28, 26, 26);
    const int Inset = 2, IconSide = 25;   // as AmsuReaderTests: 25×25 interiors, frame left out

    [Fact]
    public void Build_brand_templates_when_requested()
    {
        if (Environment.GetEnvironmentVariable("GAUGE_BUILD_BRAND") != "1") return;
        static string Cut(string fixture, PixelRect box)
        {
            var inner = new PixelRect(box.X + Inset, box.Y + Inset, box.Width - 2 * Inset, box.Height - 2 * Inset);
            return Convert.ToBase64String(ImageOps.Resample(Fixture.Load(fixture).Frames[0], inner, (double)IconSide / inner.Width).ToBytes());
        }
        var sb = new StringBuilder();
        sb.AppendLine("namespace GaugeOverlay.Core.Vision;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>The boss row's 낙인 icons (BrandIcon order), frame left out, 25×25: 바드 from nakin_bard, 도화가 from nakin_dohwa,");
        sb.AppendLine("/// 홀나/발키리 from nakin_holy (1920×1080, 보스 디버프 크기 about 100). Image.ToBytes as base64.");
        sb.AppendLine("/// Generated by BrandReaderTests.Build_brand_templates_when_requested (GAUGE_BUILD_BRAND=1); do not edit by hand.</summary>");
        sb.AppendLine("internal static class BrandTemplates");
        sb.AppendLine("{");
        sb.AppendLine("    public static readonly string?[] Icons =");
        sb.AppendLine("    [");
        sb.AppendLine($"        \"{Cut("nakin_bard", BardBox)}\",   // 바드");
        sb.AppendLine($"        \"{Cut("nakin_dohwa", DohwaBox)}\",   // 도화가");
        sb.AppendLine($"        \"{Cut("nakin_holy", HolyBox)}\",   // 홀나발키리");
        sb.AppendLine("    ];");
        sb.AppendLine("}");
        File.WriteAllText(Path.Combine(RepoRoot(), "Core", "Vision", "BrandTemplates.cs"), sb.ToString().ReplaceLineEndings("\r\n"));
    }

    // The 1080p shots as the engine reads them: HUD 110 puts the first icon at x 928, y 169–170 (as reference/빛암).
    static readonly Viewport Hd = new(0, 0, 1920, 1080);
    static readonly Fit Hud110 = new(110);

    static (Image R, double Scale, BossSlots Slots, int Line) Row(string name, int size)
    {
        var s = Geometry.BossDebuffStrip(Hd, Hud110, size);
        double scale = Geometry.BossScale(Hd, Hud110, size);
        var slots = Geometry.BossSlotsIn(Hd, Hud110, size);
        int width = Math.Min(s.Width, 600 - (s.X - 700));   // the fixtures are 600 px wide
        var r = DebuffReader.ToReference(Fixture.Load(name).Frames[0].Crop(new PixelRect(s.X - 700, s.Y - 100, width, s.Height)), scale);
        int line = AmsuReader.SnapIn(r, scale, slots, Geometry.BossDebuffLine, Geometry.BossLineSnap) ?? Geometry.BossDebuffLine;
        return (r, scale, slots, line);
    }

    [Theory]
    [InlineData("nakin_dohwa", BrandIcon.도화가)]
    [InlineData("nakin_holy", BrandIcon.홀나발키리)]
    public void The_shots_read_their_brand(string name, BrandIcon icon)
    {
        var (r, scale, slots, line) = Row(name, 100);
        Assert.Equal(icon, BrandReader.Find(r, scale, slots, line));
    }

    [Theory]
    [InlineData("nakin_dohwa", 3, 2)]
    [InlineData("nakin_holy", 5, 3)]
    public void Only_the_brand_slot_reads_as_a_brand(string name, int icons, int brandSlot)
    {
        var (r, scale, slots, line) = Row(name, 100);
        int y = (int)Math.Round(line / scale);
        var filled = AmsuReader.WalkIn(r, scale, slots, line).Filled;
        Assert.Equal(icons, filled.Count);
        for (int i = 0; i < filled.Count; i++)
        {
            var hit = BrandReader.At(r, (int)Math.Round(filled[i].Icon.X / scale), y);
            if (i == brandSlot) Assert.NotNull(hit);
            else Assert.Null(hit);
        }
    }

    // The shots' "N초" (labelled by eye on reference/낙인: 홀나/발키리 7, 7, 9, 9, 14; 도화가 4, 6, 8): their text reads at the 110% glyph
    // scale (the 보스 디버프 크기 "about 100" is the icon pitch). A value is read only when both glyph scales agree, never a wrong one.
    [Theory]
    [InlineData("nakin_holy", new[] { 7, 7, 9, 9, 14 })]
    [InlineData("nakin_dohwa", new[] { 4, 6, 8 })]
    public void The_shots_seconds_read_as_labelled_or_not_at_all(string name, int[] labelled)
    {
        var s = Geometry.BossDebuffStrip(Hd, Hud110, 100);
        var crop = Fixture.Load(name).Frames[0].Crop(new PixelRect(s.X - 700, s.Y - 100, Math.Min(s.Width, 600 - (s.X - 700)), s.Height));
        var (r, scale, slots, line) = Row(name, 100);
        var filled = AmsuReader.WalkIn(r, scale, slots, line).Filled;
        Assert.Equal(labelled.Length, filled.Count);
        double textScale = Geometry.BuffScale(Hd, 110);
        var reads = filled.Select(f => AmsuReader.ReadSeconds(crop, f.Icon, textScale, 30)).ToList();
        for (int i = 0; i < labelled.Length; i++)
            if (reads[i] is { } seconds) Assert.Equal(labelled[i], seconds);
        Assert.True(reads.Count(r => r is not null) >= labelled.Length - 1, "at most one unread");
    }

    // The 바드 crop's size is unknown: brought to reference size by its own icons (26 px against the 1080p shots' 28).
    [Fact]
    public void The_bard_crop_reads_its_brand_and_no_other_icon()
    {
        double scale = Geometry.BossScale(Hd, Hud110, 100) * BardBox.Width / DohwaBox.Width;
        var r = DebuffReader.ToReference(Fixture.Load("nakin_bard").Frames[0], scale);
        const int Pitch = 29;   // the crop's frame lines at 46, 75, 104 …
        for (int k = -3; k <= 4; k++)
        {
            var hit = BrandReader.At(r, (int)Math.Round((BardBox.X + k * Pitch) / scale), (int)Math.Round(BardBox.Y / scale));
            if (k == 0) Assert.Equal(BrandIcon.바드, hit);
            else Assert.Null(hit);
        }
    }

    // Rows without 낙인 (the 빛암 clip at every size) read none.
    [Theory]
    [InlineData("bitam_80", 80)]
    [InlineData("bitam_90", 90)]
    [InlineData("bitam_100", 100)]
    [InlineData("bitam_110", 110)]
    [InlineData("bitam_120", 120)]
    public void Rows_without_a_brand_read_none(string name, int size)
    {
        var (r, scale, slots, line) = Row(name, size);
        Assert.Null(BrandReader.Find(r, scale, slots, line));
    }

    // 대난투 moves the row under the gimmick's fill bar (AmsuDaenantuTests): the 홀나/발키리 낙인 shows there at 20 and 35 s, not
    // yet at 17 s (7 debuffs, none a 낙인).
    [Theory]
    [InlineData(0, null)]
    [InlineData(1, BrandIcon.홀나발키리)]
    [InlineData(2, BrandIcon.홀나발키리)]
    public void The_daenantu_row_reads_its_brand(int frame, BrandIcon? icon)
    {
        var hd = new Viewport(0, 0, 1920, 1080);
        var fit = new Fit(110.05);
        var s = Geometry.DaenantuDebuffStrip(hd, fit);
        var layout = AmsuLayout.Daenantu(hd, fit);
        var fixture = Fixture.Load("amsu_daenantu");
        int x = s.X - fixture.Rect[0], y = Math.Max(0, s.Y - fixture.Rect[1]);
        var strip = fixture.Frames[frame].Crop(new PixelRect(x, y, Math.Min(s.Width, fixture.Rect[2] - x), Math.Min(s.Bottom - fixture.Rect[1], fixture.Rect[3]) - y));
        var r = DebuffReader.ToReference(strip, layout.Scale);
        Assert.Equal(icon, BrandReader.Find(r, layout.Scale, layout.Slots, layout.Line));
    }

    // The watch reads 낙인 on each row as 대난투 starts and ends (the layout flips, the line snaps again on the new row).
    [Fact]
    public void The_watch_reads_the_brand_as_the_layout_flips_to_daenantu_and_back()
    {
        var s = Geometry.BossDebuffStrip(Hd, Hud110, 100);
        var usual = Fixture.Load("nakin_holy").Frames[0].Crop(new PixelRect(s.X - 700, s.Y - 100, Math.Min(s.Width, 600 - (s.X - 700)), s.Height));
        var fit = new Fit(110.05);
        var d = Geometry.DaenantuDebuffStrip(Hd, fit);
        var fixture = Fixture.Load("amsu_daenantu");
        int x = d.X - fixture.Rect[0], y = Math.Max(0, d.Y - fixture.Rect[1]);
        Image Gimmick(int frame) => fixture.Frames[frame].Crop(new PixelRect(x, y, Math.Min(d.Width, fixture.Rect[2] - x), Math.Min(d.Bottom - fixture.Rect[1], fixture.Rect[3]) - y));
        var w = new BrandWatch();
        var steps = new (AmsuLayout Layout, Image Strip, BrandIcon? Icon)[]
        {
            (AmsuLayout.Of(Hd, Hud110, 100), usual, BrandIcon.홀나발키리),
            (AmsuLayout.Daenantu(Hd, fit), Gimmick(0), null),
            (AmsuLayout.Daenantu(Hd, fit), Gimmick(1), BrandIcon.홀나발키리),
            (AmsuLayout.Of(Hd, Hud110, 100), usual, BrandIcon.홀나발키리),
        };
        for (int i = 0; i < steps.Length; i++)
        {
            w.Read(steps[i].Layout, steps[i].Strip, TimeSpan.FromSeconds(i));
            Assert.Equal(steps[i].Icon, w.Icon);
        }
    }
}
